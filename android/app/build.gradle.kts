// Same version as the Linux and macOS apps (Cargo.toml), e.g. 26.10.0.
val riffVersion: String = rootDir.resolve("../Cargo.toml").readLines()
    .first { it.startsWith("version = ") }
    .substringAfter('"').substringBefore('"')

fun versionCodeOf(version: String): Int {
    val (major, minor, patch) = version.split('.').map { it.toInt() }
    return major * 10000 + minor * 100 + patch
}

// Release signing comes from the environment (CI secrets) or local.properties.
val localProperties = Properties().apply {
    val file = rootDir.resolve("local.properties")
    if (file.exists()) file.inputStream().use { load(it) }
}

fun signingValue(name: String): String? =
    System.getenv(name) ?: localProperties.getProperty(name)

