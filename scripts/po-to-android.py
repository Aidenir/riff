#!/usr/bin/env python3
"""Convert gettext .po translations into Android values-<lang>/strings.xml.

The Android client keeps its English source strings in
android/app/src/main/res/values/strings.xml, worded like the GTK app. Every
string whose English text is a translated msgid gets that translation;
placeholders map between gettext's "{}" and Android's "%1$s". Plurals, fuzzy
and untranslated entries are skipped, and so is en.po, which renames GTK
labels.

Usage: po-to-android.py <po-dir> <res-dir>
"""

import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from importlib import import_module  # noqa: E402

parse_po = import_module("po-to-strings").parse_po

PLACEHOLDER = re.compile(r"%(\d+)\$([sd])")


def android_dir(stem: str) -> str:
    if "-" in stem:
        lang, region = stem.split("-", 1)
        return f"values-{lang}-r{region.upper()}"
    return f"values-{stem}"


def unescape(text: str) -> str:
    return text.replace("\\'", "'").replace('\\"', '"')


def escape(text: str) -> str:
    text = text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    text = text.replace("\\", "\\\\").replace("'", "\\'").replace('"', '\\"')
    if text.startswith("@") or text.startswith("?"):
        text = "\\" + text
    return text.replace("\n", "\\n")


def to_msgid(text: str):
    """English Android text to a gettext msgid, with the placeholder specs."""
    specs = PLACEHOLDER.findall(text)
    return PLACEHOLDER.sub("{}", text), specs


def from_msgstr(text: str, specs) -> str | None:
    if text.count("{}") != len(specs):
        return None
    out = text.replace("%", "%%") if specs else text
    for index, kind in specs:
        out = out.replace("{}", f"%{index}${kind}", 1)
    return out


def main() -> None:
    po_dir, res_dir = Path(sys.argv[1]), Path(sys.argv[2])
    source = ET.parse(res_dir / "values" / "strings.xml").getroot()
    strings = []
    for node in source.findall("string"):
        if node.get("translatable") == "false":
            continue
        strings.append((node.get("name"), unescape(node.text or "")))

    for old in res_dir.glob("values-*/strings.xml"):
        if old.parent.name != "values-night":
            old.unlink()
            if not any(old.parent.iterdir()):
                old.parent.rmdir()

    count = 0
    for po in sorted(po_dir.glob("*.po")):
        if po.stem == "en":
            continue
        entries = parse_po(po)
        lines = []
        for name, text in strings:
            msgid, specs = to_msgid(text)
            translated = entries.get(msgid)
            if not translated:
                continue
            value = from_msgstr(translated, specs)
            if value is None:
                continue
            lines.append(f'    <string name="{name}">{escape(value)}</string>')
        if not lines:
            continue
        folder = res_dir / android_dir(po.stem)
        folder.mkdir(parents=True, exist_ok=True)
        body = "\n".join(lines)
        (folder / "strings.xml").write_text(
            f'<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by scripts/po-to-android.py. -->\n<resources>\n{body}\n</resources>\n',
            encoding="utf-8",
        )
        count += 1
    print(f"  {count} languages")


if __name__ == "__main__":
    main()
